    /** Today in Nepal. */
    static NepaliDate today() {
        Calendar c = Calendar.getInstance(NEPAL);
        return of(c.get(Calendar.YEAR), c.get(Calendar.MONTH) + 1, c.get(Calendar.DAY_OF_MONTH));
    }

    /** @return null outside 2000–2099 BS */
    static NepaliDate of(int adYear, int adMonth, int adDay) {
        long days = epochDay(adYear, adMonth, adDay) - epochDay(1943, 4, 14);
        if (days < 0) return null;
        int y = 0;
        while (y < MONTHS.length) {
            int len = 0;
            for (int m : MONTHS[y]) len += m;
            if (days < len) break;
            days -= len;
            y++;
        }
        if (y >= MONTHS.length) return null;
        int m = 0;
        while (days >= MONTHS[y][m]) {
            days -= MONTHS[y][m];
            m++;
        }
        NepaliDate d = new NepaliDate();
        d.year = FIRST_YEAR + y;
        d.month = m + 1;
        d.day = (int) days + 1;
        d.tithi = tithiAtSunrise(adYear, adMonth, adDay);
        return d;
    }

    /** "कात्तिक २१, २०८३" */
    String dateLine() {
        return MONTH_NAMES[month - 1] + " " + digits(day) + ", " + digits(year);
    }

    /** "शुक्ल पञ्चमी", "पूर्णिमा", "औंसी" */
    String tithiName() {
        if (tithi == 15) return "पूर्णिमा";
        if (tithi == 30) return "औंसी";
        return (tithi < 15 ? "शुक्ल " : "कृष्ण ") + TITHI[(tithi - 1) % 15];
    }

    static String digits(long n) {
        String s = Long.toString(n);
        StringBuilder b = new StringBuilder();
        for (char ch : s.toCharArray()) b.append(ch >= '0' && ch <= '9' ? (char) ('०' + (ch - '0')) : ch);
        return b.toString();
    }

    /** Days since 1 Jan 1970 for a Gregorian date. */
    static long epochDay(int y, int m, int d) {
        long yy = y - (m <= 2 ? 1 : 0);
        long era = (yy >= 0 ? yy : yy - 399) / 400;
        long yoe = yy - era * 400;
        long doy = (153L * (m + (m > 2 ? -3 : 9)) + 2) / 5 + d - 1;
        long doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
        return era * 146097 + doe - 719468;
    }

    // ------------------------------------------------------------------ tithi

    private static final double LAT = 27.7172, LON = 85.3240; // Kathmandu

    static int tithiAtSunrise(int y, int m, int d) {
        double jd = epochDay(y, m, d) + 2440587.5 + sunriseUtcMinutes(y, m, d) / 1440.0;
        double e = elongation(jd);
        return Math.min(30, (int) Math.floor(e / 12.0) + 1);
    }

    /** Minutes after 00:00 UTC of that date (NOAA's simple formula). */
    private static double sunriseUtcMinutes(int y, int m, int d) {
        int n = (int) (epochDay(y, m, d) - epochDay(y, 1, 1)) + 1;
        double g = 2 * Math.PI / 365 * (n - 1);
        double eqt = 229.18 * (0.000075 + 0.001868 * Math.cos(g) - 0.032077 * Math.sin(g)
                - 0.014615 * Math.cos(2 * g) - 0.040849 * Math.sin(2 * g));
        double dec = 0.006918 - 0.399912 * Math.cos(g) + 0.070257 * Math.sin(g) - 0.006758 * Math.cos(2 * g)
                + 0.000907 * Math.sin(2 * g) - 0.002697 * Math.cos(3 * g) + 0.00148 * Math.sin(3 * g);
        double la = Math.toRadians(LAT);
        double ha = Math.toDegrees(Math.acos(Math.cos(Math.toRadians(90.833)) / (Math.cos(la) * Math.cos(dec))
                - Math.tan(la) * Math.tan(dec)));
        return 720 - 4 * (LON + ha) - eqt;
    }

