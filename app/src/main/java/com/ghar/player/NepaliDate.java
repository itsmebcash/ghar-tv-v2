    /** Moon longitude minus Sun longitude, 0–360°. */
    static double elongation(double jd) {
        double t = (jd - 2451545.0) / 36525;
        double lp = 218.3164477 + 481267.88123421 * t;
        double dd = 297.8501921 + 445267.1114034 * t;
        double ms = 357.5291092 + 35999.0502909 * t;
        double mm = 134.9633964 + 477198.8675055 * t;
        double ff = 93.2720950 + 483202.0175233 * t;
        double e = 1 - 0.002516 * t;
        double sum = 0;
        for (int[] k : MOON) {
            double arg = k[0] * dd + k[1] * ms + k[2] * mm + k[3] * ff;
            double c = k[4] * Math.pow(e, Math.abs(k[1]));
            sum += c * Math.sin(Math.toRadians(arg));
        }
        double a1 = 119.75 + 131.849 * t, a2 = 53.09 + 479264.290 * t;
        sum += 3958 * Math.sin(Math.toRadians(a1)) + 1962 * Math.sin(Math.toRadians(lp - ff))
                + 318 * Math.sin(Math.toRadians(a2));
        double moon = lp + sum / 1e6;
        double l0 = 280.46646 + 36000.76983 * t;
        double c = (1.914602 - 0.004817 * t) * Math.sin(Math.toRadians(ms))
                + (0.019993 - 0.000101 * t) * Math.sin(Math.toRadians(2 * ms))
                + 0.000289 * Math.sin(Math.toRadians(3 * ms));
        double sun = l0 + c - 0.00569;
        double r = (moon - sun) % 360;
        return r < 0 ? r + 360 : r;
    }

    /** "कात्तिक २६" (no year) */
    String monthDay() {
        return MONTH_NAMES[month - 1] + " " + digits(day);
    }

